def seed_if_empty(db: Session) -> None:
    if db.query(Event).count() > 0:
        return
    city = default_city(db)
    city_name = city.name if city else "Pittsburgh"
    city_id = city.id if city else None
    now = datetime.now(timezone.utc).replace(tzinfo=None)
    for item in PITTSBURGH_SEEDS:
        starts = (now + timedelta(days=item["offset_days"])).replace(
            hour=item["hour"], minute=0, second=0, microsecond=0
        )
        ends = starts + timedelta(hours=item["duration_hours"])
        db.add(
            Event(
                title=item["title"],
                description=item["description"],
                lat=item["lat"],
                lng=item["lng"],
                address=item["address"],
                city=city_name,
                city_id=city_id,
                starts_at=starts,
                ends_at=ends,
                people_min=item["people_min"],
                people_max=item["people_max"],
                cost_estimate=item["cost_estimate"],
                tags=dump_tags(item["tags"]),
                source="ai",
                source_url=None,
            )
        )
    db.commit()
